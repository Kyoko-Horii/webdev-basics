// ============ 1. SHOW/HIDE LESSONS ============
function showLesson(id, link) {
  document.querySelectorAll('.lesson').forEach(l => l.classList.remove('active'));
  document.getElementById(id).classList.add('active');
  document.querySelectorAll('.nav-link').forEach(a => a.classList.remove('active'));
  link.classList.add('active');
  window.scrollTo({ top: 0, behavior: 'smooth' });
}

// ============ 2. LIVE CODE EDITOR ============
function runCode(btn) {
  const editor = btn.closest('.editor');
  const textarea = editor.querySelector('textarea');
  const iframe = editor.querySelector('iframe');
  const doc = iframe.contentDocument || iframe.contentWindow.document;
  doc.open();
  doc.write(textarea.value);
  doc.close();
}

window.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('.editor').forEach(editor => {
    const ta = editor.querySelector('textarea');
    const btn = editor.querySelector('.run-btn');
    if (ta && btn) runCode(btn);
  });
});

// ============ 3. THEME TOGGLE (Dark/Light) ============
function toggleTheme() {
  const body = document.body;
  const btn = document.getElementById('themeToggle');
  body.classList.toggle('light-mode');
  const isLight = body.classList.contains('light-mode');
  btn.textContent = isLight ? '☀️' : '🌙';
  btn.title = isLight ? 'Switch to Dark Mode' : 'Switch to Light Mode';
  try { localStorage.setItem('webdev-theme', isLight ? 'light' : 'dark'); } catch (e) {}
}

window.addEventListener('DOMContentLoaded', () => {
  try {
    const saved = localStorage.getItem('webdev-theme');
    if (saved === 'light') {
      document.body.classList.add('light-mode');
      const btn = document.getElementById('themeToggle');
      if (btn) { btn.textContent = '☀️'; btn.title = 'Switch to Dark Mode'; }
    }
  } catch (e) {}
});

// ============ 5. MOBILE SIDEBAR (HAMBURGER) ============
function toggleSidebar() {
  const aside = document.getElementById('sidebar');
  const overlay = document.querySelector('.sidebar-overlay');
  const isOpen = aside.classList.toggle('open');
  if (overlay) overlay.classList.toggle('active', isOpen);
  document.body.classList.toggle('sidebar-open', isOpen);
}

function closeSidebar() {
  const aside = document.getElementById('sidebar');
  const overlay = document.querySelector('.sidebar-overlay');
  aside.classList.remove('open');
  if (overlay) overlay.classList.remove('active');
  document.body.classList.remove('sidebar-open');
}

// Auto-close drawer when a lesson link is clicked (mobile only)
document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('.nav-link').forEach(link => {
    link.addEventListener('click', () => {
      if (window.innerWidth <= 900) closeSidebar();
    });
  });

  // Close on Escape key
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') closeSidebar();
  });

  // Auto-close if resized to desktop
  window.addEventListener('resize', () => {
    if (window.innerWidth > 900) closeSidebar();
  });
});

